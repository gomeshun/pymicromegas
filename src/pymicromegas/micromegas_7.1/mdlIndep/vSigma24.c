static double T_; // temperature in GeV units
double const m=1; // pass of phi

static double vSigmaIntegrand( double sqrtS) 
{ 
  if(sqrtS<=2*m) return 0;
  double pcm=decayPcm(sqrtS,m,m); 
  double nEq=m*m*T_/(2*M_PI*M_PI)*bessK2(m/T_); 
//  return    T_/(4*pow(M_PI,4))*pow(pcm*sqrtS,2)*sigma24(pcm)*bessK1(sqrtS/T_)/nEq/nEq* /*Gondolo,Gelmini Nuclear Physics B360 (1991) 145 */ exp(2*m/T_);  
//  bessK?(x) = exp(-x)*sqrt(M_PI/(2*x))*K?pol(1/x) 
    return    T_/(4*pow(M_PI,4))*pow(pcm*sqrtS,2)*sigma24(pcm)*   
            K1pol(T_/sqrtS)/K2pol(T_/m)/K2pol(T_/m)* exp(-(sqrtS-4*m)/T_)/sqrt(M_PI*sqrtS*T_/m/m/2)/T_/T_*pow(2*M_PI*M_PI,2); 
}

static double vSigma24(double T) // vSigma24*exp(2*m/T) 
{  
  T_=T;
  double eps=1E-3;
  return  simpson(vSigmaIntegrand, 4*m,4*m+10*T,1E-3,NULL); 
}

   
